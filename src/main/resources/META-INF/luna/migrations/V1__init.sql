-- Baseline for clean installation and databases created by the legacy ActiveDocs loader.
create table if not exists ${activeDoc:panel_renders} (
    id bigint generated by default as identity primary key,
    name varchar(255),
    description varchar(255),
    field_ids text[],
    "limit" integer,
    show_actions boolean
);

alter table ${activeDoc:panel_renders} add column if not exists show_actions boolean;

create table if not exists ${activeDoc:panels} (
    id bigint generated by default as identity primary key,
    name varchar(255),
    description varchar(255),
    display_name varchar(255),
    qs text,
    author_id bigint,
    updater_id bigint,
    created timestamp(6),
    updated timestamp(6),
    disabled boolean,
    priority integer,
    project_ids bigint[],
    issue_type_ids bigint[],
    render_id bigint references ${activeDoc:panel_renders}(id) on delete cascade
);

alter table ${activeDoc:panels} add column if not exists render_id bigint references ${activeDoc:panel_renders}(id) on delete cascade;
